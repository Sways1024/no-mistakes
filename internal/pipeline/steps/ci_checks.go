type lastFixedIssues struct {
	Checks        []string `json:"checks,omitempty"`
	MergeConflict bool     `json:"mergeConflict,omitempty"`
}

// pollInterval returns the polling interval based on elapsed time since CI monitoring started.
// 30s for first 5min, 60s for 5-15min, 120s after.
func pollInterval(elapsed time.Duration) time.Duration {
	switch {
	case elapsed < 5*time.Minute:
		return 30 * time.Second
	case elapsed < 15*time.Minute:
		return 60 * time.Second
	default:
		return 120 * time.Second
	}
}

// A provider query that fails the same way on every poll is deterministic
// breakage (expired auth, an incompatible gh version, a renamed repo), not
// weather. persistentPollErrPolls and persistentPollErrWindow together decide
// when the monitor stops silently retrying such a failure and parks for a
// decision: ten consecutive identical failures rules out a blip, and the
// half-hour floor outlasts routine provider outages and rate-limit windows.
// Both must be met, so a burst of identical errors at the fast 30s cadence
// still waits out the window. Without this gate a persistent failure retried
// invisibly until the CI idle timeout - up to a week (#666).
const (
	persistentPollErrPolls  = 10
	persistentPollErrWindow = 30 * time.Minute
)

// pollErrStreak tracks consecutive identical failures of one provider query in
// the CI polling loop. Identity is the exact error string: the deterministic
// failures the escalation targets repeat verbatim on every poll (the gh
// backend reports them all as an exit status on the same command), while a
// message that varies between polls is a condition still changing. A changed
// message or an interleaved success therefore restarts the streak, which fails
// toward the pre-existing keep-polling behavior - strictness can only delay
// the park, never park a recovering provider.
type pollErrStreak struct {
	lastErr string    // message of the most recent failure
	count   int       // consecutive polls that failed with lastErr
	since   time.Time // when the current streak began
}

// observe records one failed poll and reports whether the failure has now
// repeated identically for persistentPollErrPolls polls spanning at least
// persistentPollErrWindow.
func (s *pollErrStreak) observe(now time.Time, err error) bool {
	if msg := err.Error(); msg != s.lastErr {
		*s = pollErrStreak{lastErr: msg, since: now}
	}
	s.count++
	return s.count >= persistentPollErrPolls && now.Sub(s.since) >= persistentPollErrWindow
}

func (s *pollErrStreak) reset() { *s = pollErrStreak{} }

// hasFailingChecks returns true if any CI check is in the fail bucket.
func hasFailingChecks(checks []scm.Check) bool {
	for _, c := range checks {
		if c.Failing() {
			return true
		}
	}
	return false
}

// hasPendingChecks returns true if any CI check is still running or queued.
func hasPendingChecks(checks []scm.Check) bool {
	for _, c := range checks {
		if c.Pending() {
			return true
		}
	}
	return false
}

func hasUnresolvedChecks(checks []scm.Check) bool {
	for _, c := range checks {
		switch c.Bucket {
		case scm.CheckBucketPass, scm.CheckBucketFail, scm.CheckBucketSkip:
		default:
			return true
		}
	}
	return false
}

func allChecksPassed(checks []scm.Check) bool {
	if len(checks) == 0 {
		return false
	}
	for _, c := range checks {
		if c.Bucket != scm.CheckBucketPass && c.Bucket != scm.CheckBucketSkip {
			return false
		}
	}
	return true
}

// failingCheckNames returns the names of failing checks.
func failingCheckNames(checks []scm.Check) []string {
	var names []string
	for _, c := range checks {
		if c.Failing() {
			names = append(names, c.Name)
		}
	}
	return names
}

// terminalFailureCompletionTimes snapshots when each terminally failed check
// finished, so a later poll can tell that CI has re-run since the fix push.
//
// It covers the whole terminal-failure set rather than just the fail bucket
// because a cancelled check can be a fix target too (see the CI step's
// fixTargets). Keying the snapshot on the fail bucket alone would leave a
// cancelled-only fix round with no completion evidence at all, and the step
// would then have no way to notice its own re-run.
func terminalFailureCompletionTimes(checks []scm.Check) map[string]time.Time {
	completedAt := make(map[string]time.Time)
	for _, c := range checks {
		if !checkFailedTerminally(c) {
			continue
		}
		if c.CompletedAt.IsZero() {
			continue
		}
		previous := completedAt[c.Name]
		if previous.IsZero() || c.CompletedAt.After(previous) {
			completedAt[c.Name] = c.CompletedAt
		}
	}
	if len(completedAt) == 0 {
		return nil
	}
	return completedAt
}

func terminalFailureCompletedAfter(checks []scm.Check, after map[string]time.Time) bool {
	if len(after) == 0 {
		return false
	}
	for _, c := range checks {
		if !checkFailedTerminally(c) || c.CompletedAt.IsZero() {
			continue
		}
		previous, ok := after[c.Name]
		if ok && c.CompletedAt.After(previous) {
			return true
		}
	}
	return false
}

func pendingCheckMatchesLastFixed(checks []scm.Check, lastFixedChecks string) bool {
	issues, ok := decodeLastFixedChecks(lastFixedChecks)
	if !ok {
		return false
	}

	failedNames := map[string]struct{}{}
	for _, name := range issues.Checks {
		if name == "" {
			continue
		}
		failedNames[name] = struct{}{}
	}
	if len(failedNames) == 0 {
		return issues.MergeConflict && hasPendingChecks(checks)
	}

	for _, c := range checks {
		if !c.Pending() {
			continue
		}
		if _, ok := failedNames[c.Name]; ok {
			return true
		}
	}

	return false
}

func encodeLastFixedChecks(failing []string, mergeConflict bool) string {
	if len(failing) == 0 && !mergeConflict {
		return ""
	}
	encoded, err := json.Marshal(lastFixedIssues{Checks: failing, MergeConflict: mergeConflict})
	if err != nil {
		return ""
	}
	return string(encoded)
}

func decodeLastFixedChecks(raw string) (lastFixedIssues, bool) {
	if raw == "" {
		return lastFixedIssues{}, false
	}
	var issues lastFixedIssues
	if err := json.Unmarshal([]byte(raw), &issues); err != nil {
		return lastFixedIssues{}, false
	}
	if len(issues.Checks) == 0 && !issues.MergeConflict {
		return lastFixedIssues{}, false
	}
	return issues, true
}

func ciFailureOutcome(failing []string, mergeConflict bool, summary string) *pipeline.StepOutcome {
	findings := Findings{Summary: summary}
	for _, name := range failing {
		findings.Items = append(findings.Items, Finding{
			Severity:    "warning",
			Description: fmt.Sprintf("CI check failing: %s", name),
		})
	}
	if mergeConflict {
		findings.Items = append(findings.Items, Finding{
			Severity:    "warning",
			Description: "PR has merge conflicts with the base branch",
		})
	}
	findingsJSON, _ := json.Marshal(findings)
	return &pipeline.StepOutcome{
		NeedsApproval: true,
		Findings:      string(findingsJSON),
	}
}

// ciPersistentPollErrorOutcome parks the run for a decision when one of the
// monitor's provider queries keeps failing identically (see pollErrStreak).
// It is an ask-user gate rather than a hard failure so a long provider outage
// stays resumable once it clears; what it replaces is a silent retry loop that
// stalled the run until the idle timeout. what matches the per-poll warning
// vocabulary ("CI", "PR state", "mergeable state").
func ciPersistentPollErrorOutcome(what string, streak *pollErrStreak, now time.Time) *pipeline.StepOutcome {
	findings := Findings{
		Summary: fmt.Sprintf("CI monitor cannot check %s", what),
		Items: []Finding{{
			Severity: "warning",
			Description: fmt.Sprintf("could not check %s: %s (failed identically on %d consecutive polls over %s)",
				what, streak.lastErr, streak.count, now.Sub(streak.since).Round(time.Minute)),
			Action: types.ActionAskUser,
		}},
	}
	findingsJSON, _ := json.Marshal(findings)
	return &pipeline.StepOutcome{
		NeedsApproval: true,
		Findings:      string(findingsJSON),
	}
}

